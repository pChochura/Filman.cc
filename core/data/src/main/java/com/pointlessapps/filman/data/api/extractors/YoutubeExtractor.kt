package com.pointlessapps.filman.data.api.extractors

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.exceptions.ContentNotAvailableException

data class YoutubeExtractionResult(
    val videos: List<ExtractedVideo> = emptyList(),
    val title: String? = null,
    val description: String? = null,
    val durationMs: Long? = null,
    val thumbnailUrl: String? = null,
)

object YoutubeExtractor : EmbedExtractor {
    override suspend fun extractVideo(embedUrl: String): List<ExtractedVideo> =
        extractYoutubeVideo(embedUrl).videos

    suspend fun extractYoutubeVideo(embedUrl: String): YoutubeExtractionResult =
        withContext(Dispatchers.IO) {
            try {
                val service = ServiceList.YouTube
                val streamExtractor = service.getStreamExtractor(embedUrl)

                try {
                    streamExtractor.fetchPage()
                } catch (e: ContentNotAvailableException) {
                    if (e.message?.contains("reload") == true) {
                        streamExtractor.fetchPage()
                    } else {
                        throw e
                    }
                }

                val title = runCatching { streamExtractor.name }.getOrNull()
                val description = runCatching { streamExtractor.description?.content }.getOrNull()
                val durationMs = runCatching {
                    val len = streamExtractor.length
                    if (len > 0) len * 1000L else null
                }.getOrNull()
                val thumbnailUrl = runCatching {
                    streamExtractor.thumbnails.lastOrNull()?.url
                }.getOrNull()

                val subtitles =
                    try {
                        streamExtractor.subtitlesDefault.map { subtitle ->
                            Subtitle(
                                url = subtitle.content,
                                label =
                                    subtitle.displayLanguageName +
                                        if (subtitle.isAutoGenerated) {
                                            " (Auto)"
                                        } else {
                                            ""
                                        },
                                language = subtitle.languageTag,
                            )
                        }
                    } catch (e: Exception) {
                        emptyList()
                    }

                val audioStream =
                    try {
                        streamExtractor.audioStreams
                            .maxByOrNull {
                                it.averageBitrate
                            }?.content
                    } catch (e: Exception) {
                        null
                    }
                val videoOnly =
                    try {
                        streamExtractor.videoOnlyStreams
                            .sortedByDescending {
                                it.resolution
                                    .replace(Regex("0p\\d+$"), "1")
                                    .replace(Regex("[^0-9]"), "")
                                    .toIntOrNull() ?: 0
                            }.map { stream ->
                                ExtractedVideo(
                                    url = stream.content,
                                    audioUrl = audioStream,
                                    serverName = "YouTube",
                                    quality = stream.resolution,
                                    subtitles = subtitles,
                                )
                            }
                    } catch (e: Exception) {
                        emptyList()
                    }

                val mixed =
                    try {
                        streamExtractor.videoStreams
                            .sortedByDescending {
                                it.resolution
                                    .replace(Regex("0p\\d+$"), "1")
                                    .replace(Regex("[^0-9]"), "")
                                    .toIntOrNull() ?: 0
                            }.map { stream ->
                                ExtractedVideo(
                                    url = stream.content,
                                    audioUrl = null,
                                    serverName = "YouTube",
                                    quality = stream.resolution,
                                    subtitles = subtitles,
                                )
                            }
                    } catch (e: Exception) {
                        emptyList()
                    }

                val videos = (videoOnly + mixed).distinctBy { it.quality }
                YoutubeExtractionResult(
                    videos = videos,
                    title = title,
                    description = description,
                    durationMs = durationMs,
                    thumbnailUrl = thumbnailUrl,
                )
            } catch (e: Exception) {
                e.printStackTrace()
                YoutubeExtractionResult()
            }
        }
}
