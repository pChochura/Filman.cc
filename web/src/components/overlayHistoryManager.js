/**
 * Coordinates browser history state with Tiwi overlay menus so that:
 * 1. The mobile/system back button closes the overlay menu (or nested submenu)
 *    instead of navigating away or popping the underlying screen stack.
 * 2. Closing via UI (backdrop click, close button, menu selection) pops the
 *    overlay history entry cleanly without triggering ghost popstate navigation.
 */

let overlayStack = [];
let ignorePopCount = 0;
let isPoppingFromPopstate = false;

export function pushOverlayHistoryState(dismissFn) {
  if (typeof window === 'undefined') return;
  overlayStack.push(dismissFn);
  try {
    window.history.pushState(
      {
        ...window.history.state,
        __tiwiOverlay: true,
        __tiwiOverlayDepth: overlayStack.length,
      },
      '',
    );
  } catch {
    // Some restricted environments / webviews may throw on pushState
  }
}

export function popOverlayHistoryByUI(count = 1) {
  if (typeof window === 'undefined' || isPoppingFromPopstate || overlayStack.length === 0) return;
  const toPop = Math.min(count, overlayStack.length);
  for (let i = 0; i < toPop; i += 1) {
    overlayStack.pop();
  }
  ignorePopCount += toPop;
  try {
    window.history.go(-toPop);
  } catch {
    ignorePopCount -= toPop;
  }
}

export function popAllOverlayHistoryByUI() {
  if (typeof window === 'undefined' || isPoppingFromPopstate || overlayStack.length === 0) return;
  const count = overlayStack.length;
  overlayStack = [];
  ignorePopCount += count;
  try {
    window.history.go(-count);
  } catch {
    ignorePopCount -= count;
  }
}

export function isHandlingPopstate() {
  return isPoppingFromPopstate;
}

export function hasActiveOverlay() {
  return overlayStack.length > 0;
}

export function handleOverlayPopstate() {
  if (ignorePopCount > 0) {
    ignorePopCount -= 1;
    return true; // Ignore the popstate generated by history.go(-count) from UI
  }

  if (overlayStack.length > 0) {
    const dismissFn = overlayStack.pop();
    isPoppingFromPopstate = true;
    try {
      if (typeof dismissFn === 'function') {
        dismissFn();
      }
    } finally {
      isPoppingFromPopstate = false;
    }
    return true; // Popstate was consumed by dismissing overlay / submenu
  }

  return false; // No overlay active, pass event to normal router
}

export function resetOverlayHistory() {
  overlayStack = [];
  ignorePopCount = 0;
  isPoppingFromPopstate = false;
}
